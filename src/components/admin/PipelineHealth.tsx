// ─── Types ──────────────────────────────────────────────────────────────────

type StreamKey = "guest" | "signed_in" | "admin";

interface StreamStats {
  last_at: string | null;
  hours_since: number | null;
  count_24h: number;
  count_7d: number;
  count_prev_7d: number;
  total: number;
}

interface DailyRow {
  day: string;
  guest: number;
  signed_in: number;
  admin: number;
}

interface Health {
  generated_at: string;
  streams: Record<StreamKey, StreamStats>;
  daily: DailyRow[];
}

interface Alert {
  id: string;
  stream: string;
  severity: "warn" | "critical";
  message: string;
  hours_since: number | null;
  detected_at: string;
  /** Null while the outage is ongoing; stamped by pipeline_health_check() once
   *  the stream produces a row again. */
  resolved_at: string | null;
}

interface PolicyRow {
  table: string;
  policy: string;
  cmd: string;
  roles: string;
  qual: string | null;
  with_check: string | null;
}


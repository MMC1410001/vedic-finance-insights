import {
  Activity, AlertTriangle, RefreshCw, ChevronDown, ChevronUp,
  ShieldCheck, FlaskConical, Check, X, Loader2,
} from "lucide-react";
import {
  ResponsiveContainer, BarChart, Bar, XAxis, YAxis, Tooltip, CartesianGrid, Legend,
} from "recharts";
import { createClient } from "@supabase/supabase-js";

/**
 * Pipeline Health — is the kundali write path actually working right now?
 *
 * Built after a three-day outage nobody noticed: on 2026-08-18 the RLS hardening
 * in migrations 012/013 broke guest saves (INSERT ... RETURNING hit SELECT
 * policies that no guest row matched). Guest volume went 12 -> 3 -> 0 -> 0 -> 0
 * while signed-in volume held at ~30/day, so every aggregate number stayed green
 * and the panel's empty list was indistinguishable from a quiet day.
 *
 * Hence the three design rules here:
 *   1. Report each stream separately. Never a combined total.
 *   2. Never render a zero where the truth is "the request failed".
 *   3. Give the operator a way to test the write path directly (the canary),
 *      instead of inferring health from an absence of rows.
 *
 * Data comes through the admin edge function (service role). Direct browser
 * reads of kundli_reports are RLS-gated and were the original source of the
 * "looks empty, is actually blocked" confusion.
 */

